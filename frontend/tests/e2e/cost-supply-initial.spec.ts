/** Initial004 configuration through ordinary web administration on a separate empty-costs PostgreSQL fixture. */
import { readFileSync } from "node:fs";
import { expect, test } from "@playwright/test";

test.skip(!process.env.COSTS_INITIAL_E2E, "Requires seed_costs_reference.py --without-costs on another empty synthetic database.");
test("create supply and initial published calendar, calculate and reload", async ({ page }) => {
  const password = readFileSync(process.env.IDENTITY_E2E_PASSWORD_FILE!, "utf8").replace(/\n$/, "");
  await page.goto("/ingreso/");
  await page.getByLabel("Correo", { exact: true }).fill("admin-active@example.test");
  await page.getByLabel("Contraseña", { exact: true }).fill(password);
  await page.getByRole("button", { name: "Ingresar", exact: true }).click();
  await expect(page).toHaveURL(/\/cuenta\/$/);
  await page.getByLabel("Contraseña actual", { exact: true }).fill(password);
  await page.getByLabel("Nueva contraseña", { exact: true }).fill(password + " renewed");
  await page.getByLabel("Confirmar nueva contraseña", { exact: true }).fill(password + " renewed");
  await page.getByRole("button", { name: "Cambiar contraseña", exact: true }).click();
  await expect(page).toHaveURL(/\/ingreso\/$/);
  await page.getByLabel("Correo", { exact: true }).fill("admin-active@example.test");
  await page.getByLabel("Contraseña", { exact: true }).fill(password + " renewed");
  await page.getByRole("button", { name: "Ingresar", exact: true }).click();
  await expect(page).toHaveURL(/\/cuenta\/$/);
  await page.goto("/administracion/costos/");
  await expect(page.getByRole("heading", { name: "Suministro general · Alta inicial", exact: true })).toBeVisible();
  await page.getByLabel("Tablero general", { exact: true }).fill("synthetic:initial-board");
  await page.getByLabel("UUID del medidor general", { exact: true }).fill("00000000-0000-0000-0000-000000000001");
  await page.getByLabel("Distribuidora", { exact: true }).fill("synthetic");
  await page.getByLabel("Ubicación del suministro", { exact: true }).fill("synthetic");
  await page.getByLabel("Condiciones de conexión", { exact: true }).fill("synthetic");
  await page.getByRole("textbox", { name: "Fuentes documentales del suministro (una por línea)", exact: true }).fill("synthetic:supply");
  await page.getByRole("button", { name: "Confirmar suministro", exact: true }).click();
  await expect(page.getByRole("heading", { name: "Suministro general · Revisión 1", exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByLabel("Tablero general", { exact: true })).toHaveValue("synthetic:initial-board");
  await page.getByLabel("Condiciones territoriales", { exact: true }).fill("Synthetic initial calendar");
  await page.getByRole("textbox", { name: "Fuentes del perfil", exact: true }).fill("synthetic:profile");
  await page.getByRole("combobox", { name: /^Estado de la nueva revisión/ }).selectOption("published");
  await page.getByRole("button", { name: "Añadir segmento", exact: true }).click();
  await page.getByLabel("Inicio de vigencia 1", { exact: true }).fill("2025-01-01T00:00:00Z");
  await page.getByRole("textbox", { name: "Fuentes del segmento 1", exact: true }).fill("synthetic:segment");
  await page.getByLabel("Versión del calendario de punta 1", { exact: true }).fill("synthetic-peak-v1");
  await page.getByLabel("Meses de punta 1 (1–12 separados por coma)", { exact: true }).fill("4");
  await page.getByLabel("Días de punta 1 (lunes=0, domingo=6)", { exact: true }).fill("0");
  await page.getByLabel("Versión de política mensual 1", { exact: true }).fill("synthetic-month-v1");
  await page.getByRole("textbox", { name: "Fuentes de política mensual 1", exact: true }).fill("synthetic:month");
  await page.getByRole("button", { name: "Añadir cargo al segmento 1", exact: true }).click();
  await page.getByLabel("Código cargo 1.1", { exact: true }).fill("energy");
  await page.getByLabel("Precio cargo 1.1", { exact: true }).fill("100");
  await page.getByRole("textbox", { name: "Fuentes cargo 1.1", exact: true }).fill("synthetic:energy");
  await page.getByRole("button", { name: "Confirmar nueva revisión de perfil", exact: true }).click();
  await expect(page.getByRole("button", { name: "Copiar calendario revisión 1", exact: true })).toBeVisible();
  await page.getByLabel("Inicio del ciclo con offset", { exact: true }).fill("2026-01-01T00:00:00Z");
  await page.getByLabel("Fin del ciclo con offset", { exact: true }).fill("2026-01-01T01:00:00Z");
  await page.getByRole("button", { name: "Confirmar cálculo", exact: true }).click();
  await expect(page.getByText("Costo completo: 100000 CLP", { exact: true })).toBeVisible();
  await page.reload();
  await expect(page.getByText("Costo completo: 100000 CLP", { exact: true })).toBeVisible();
});
