/** Real full-calendar publications and optimistic supply edits retain earlier calculations unchanged. */
import { expect, test } from "@playwright/test";
import { loginCosts, mutate } from "./costs.helpers";

test.skip(!process.env.COSTS_E2E, "Requires the separate renewed synthetic costs fixture.");
test("supply conflict preserves draft; full calendar, retroactive revision and draft preserve history", async ({ page }) => {
  await loginCosts(page);
  const cycles = await (await page.request.get("/api/v1/costs/cycles")).json();
  const oldId = new URL(page.url()).searchParams.get("calculation");
  const calendars = await (await page.request.get("/api/v1/costs/profiles")).json();
  if (calendars.latest_version.revision !== 1) {
    const { id, revision, previous_version_id, created_at, retain_until, ...initial } = calendars.items.find((value: { revision: number }) => value.revision === 1);
    initial.expected_previous_version_id = calendars.latest_version_id;
    expect((await mutate(page, "profiles", initial)).status()).toBe(201);
    await page.reload();
  }
  const old = await (await page.request.get(`/api/v1/costs/calculations/${oldId}`)).json();
  const supplyResponse = await page.request.get("/api/v1/costs/supply");
  const supply = await supplyResponse.json();
  const { id, revision, created_at, retain_until, actor_ref, ...supplyBody } = supply;
  const remote = await mutate(page, "supply", { ...supplyBody, location: "synthetic concurrent edit" }, "PUT", { "If-Match": supplyResponse.headers().etag });
  expect(remote.status()).toBe(200);
  await page.getByLabel("Ubicación del suministro", { exact: true }).fill("synthetic local draft");
  const conflict = page.waitForResponse(r => r.url().endsWith("/costs/supply") && r.request().method() === "PUT");
  await page.getByRole("button", { name: "Confirmar suministro", exact: true }).click();
  expect((await conflict).status()).toBe(412);
  await expect(page.getByLabel("Ubicación del suministro", { exact: true })).toHaveValue("synthetic local draft");
  await page.getByRole("button", { name: "Revisar suministro actual", exact: true }).click();
  await expect(page.getByLabel("Ubicación del suministro", { exact: true })).toHaveValue("synthetic concurrent edit");
  await page.getByRole("textbox", { name: "Diferencias del punto de medición (una por línea)", exact: true }).fill("synthetic:distinct-meter-point");
  await page.getByRole("button", { name: "Confirmar suministro", exact: true }).click();
  await expect(page.getByRole("heading", { name: /Suministro general/ })).toContainText(`Revisión ${supply.revision + 2}`);
  await page.reload();
  await expect(page.getByRole("textbox", { name: "Diferencias del punto de medición (una por línea)", exact: true })).toHaveValue("synthetic:distinct-meter-point");
  await page.getByRole("button", { name: "Copiar segmento 1", exact: true }).click();
  await page.getByLabel("Fin de vigencia 1 (vacío significa abierto)", { exact: true }).fill("2026-07-01T00:00:00Z");
  await page.getByLabel("Inicio de vigencia 2", { exact: true }).fill("2026-07-01T00:00:00Z");
  await page.getByLabel("Precio cargo 2.1", { exact: true }).fill("110");
  await page.getByRole("combobox", { name: /^Estado de la nueva revisión/ }).selectOption("published");
  const v2Response = page.waitForResponse(r => r.url().endsWith("/costs/profiles") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Confirmar nueva revisión de perfil", exact: true }).click();
  const v2 = await (await v2Response).json();
  expect(v2.segments).toHaveLength(2);
  await expect(page.getByText(new RegExp(`Última guardada: ${v2.id}`))).toBeVisible();
  await page.getByLabel("Precio cargo 1.1", { exact: true }).fill("105");
  const v3Response = page.waitForResponse(r => r.url().endsWith("/costs/profiles") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Confirmar nueva revisión de perfil", exact: true }).click();
  const v3 = await (await v3Response).json();
  await expect(page.getByText(new RegExp(`Última guardada: ${v3.id}`))).toBeVisible();
  await page.getByLabel("Motivo del recálculo", { exact: true }).fill("synthetic retroactive profile correction");
  const calcResponse = page.waitForResponse(r => r.url().endsWith("/costs/calculations") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Confirmar cálculo", exact: true }).click();
  const recalculated = await (await calcResponse).json();
  expect(recalculated.complete_total).toBe("105000");
  expect(recalculated.snapshot.profile_id).toBe(v3.id);
  await expect(page.getByText("Costo completo: 105000 CLP", { exact: true })).toBeVisible();
  expect((await (await page.request.get(`/api/v1/costs/calculations/${old.id}`)).json()).complete_total).toBe(old.complete_total);
  await page.getByRole("combobox", { name: /^Estado de la nueva revisión/ }).selectOption("draft");
  await page.getByLabel("Precio cargo 1.1", { exact: true }).fill("120");
  const draftResponse = page.waitForResponse(r => r.url().endsWith("/costs/profiles") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Confirmar nueva revisión de perfil", exact: true }).click();
  const draft = await (await draftResponse).json();
  await expect(page.getByText(new RegExp(`Última guardada: ${draft.id} · Publicada seleccionada: ${v3.id}`))).toBeVisible();
  const profile = await (await page.request.get("/api/v1/costs/profiles")).json();
  const { id: profileId, revision: profileRevision, previous_version_id, created_at: profileCreated, retain_until: profileRetained, actor_ref: profileActor, ...full } = profile.latest_version;
  full.expected_previous_version_id = draft.id; full.publication_state = "published"; full.segments[0].charges[0].unit_price = "100";
  const winners = await Promise.all([mutate(page, "profiles", full), mutate(page, "profiles", full)]);
  expect(winners.map(r => r.status()).sort()).toEqual([201, 409]);
  const staleResponse = page.waitForResponse(r => r.url().endsWith("/costs/profiles") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Confirmar nueva revisión de perfil", exact: true }).click();
  expect((await staleResponse).status()).toBe(409);
  await expect(page.getByLabel("Precio cargo 1.1", { exact: true })).toHaveValue("120");
  await page.getByRole("button", { name: "Revisar último calendario", exact: true }).click();
  await expect(page.getByLabel("Precio cargo 1.1", { exact: true })).toHaveValue("100");
  await page.reload();
  await page.getByLabel("Motivo del recálculo", { exact: true }).fill("synthetic restored reference");
  await page.getByRole("button", { name: "Confirmar cálculo", exact: true }).click();
  await expect(page.getByText("Costo completo: 100000 CLP", { exact: true })).toBeVisible();
});
