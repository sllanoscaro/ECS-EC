"""Closed schema-v1 envelopes; strict UTC, finite JSON, typed counts and <=16KiB bytes.

The packaged schema is generated by copying the normative007 contract; the contract
suite checks equality. Regenerate with `cp specs/007-observabilidad-externa/contracts/
log-event.schema.json backend/src/ecs_ec/observability/log-event.schema.json`.
"""

import json
import re
from datetime import datetime
from importlib.resources import files
from jsonschema import Draft202012Validator, FormatChecker
from ecs_ec.observability.sanitization import primitives

SCHEMA = json.loads(files(__package__).joinpath("log-event.schema.json").read_text())
VALIDATOR = Draft202012Validator(SCHEMA, format_checker=FormatChecker())
CODES = frozenset(SCHEMA["properties"]["code"]["enum"])
OPERATIONS = frozenset(SCHEMA["properties"]["operation"]["enum"])
STAGES = frozenset(SCHEMA["properties"]["stage"]["enum"])
MODULES = frozenset(SCHEMA["properties"]["source_module"]["enum"])


class RejectedEvent(ValueError):
    """Fixed safe diagnostic; never attach source data or raw validation errors."""


def serialize(event: dict) -> bytes:
    """Validate/copy the safe envelope and produce immutable UTF8 bytes before any sink.

    Unknown code text becomes unclassified; unknown fields/types reject the entire
    envelope. No caller payload is modified. All rejections carry only a fixed code.
    """
    try:
        primitives(event)
        candidate = dict(event)
        if type(candidate.get("code")) is str and candidate["code"] not in CODES:
            candidate["code"] = "unclassified"
        for timestamp in (candidate.get("timestamp"), *((candidate.get("health") or {}).get(k) for k in ("last_log_collector_success", "last_trace_export_success"))):
            if timestamp is not None:
                if not re.fullmatch(r"[0-9]{4}-[0-9]{2}-[0-9]{2}T[0-9]{2}:[0-9]{2}:[0-9]{2}(?:\.[0-9]{1,9})?Z", timestamp):
                    raise ValueError()
                datetime.fromisoformat(timestamp)
        if not VALIDATOR.is_valid(candidate):
            raise ValueError()
        if candidate["health"] is not None and candidate["event"] not in {"telemetry.heartbeat", "policy.changed"}:
            raise ValueError()
        if candidate["event"] == "execution.completed" and candidate["outcome"] == "unexpected_error" and candidate["counts"] is not None:
            raise ValueError()
        data = json.dumps(candidate, ensure_ascii=False, allow_nan=False, separators=(",", ":")).encode("utf-8")
        if len(data) > 16384:
            raise ValueError()
        return data
    except Exception:
        raise RejectedEvent("schema_rejected") from None
