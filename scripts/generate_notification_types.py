"""Generate008 readonly TypeScript and packaged runtime contract from its approved OpenAPI.

Run uv run --locked python scripts/generate_notification_types.py from repository root.
The shared wire renderer preserves exact unions/decimal strings; semantic constraints
remain validated by the server, not inferred from TypeScript types.
"""

import json
from pathlib import Path

from generate_consumption_types import wire_type


def main():
    """Regenerate only008 declarations/schema; never read accounts, data, credentials or network."""
    root = Path(__file__).resolve().parents[1]
    source = root / "specs/008-notificaciones-programables/contracts/openapi.json"
    schemas = json.loads(source.read_text())["components"]["schemas"]
    lines = [
        "/** Generated by scripts/generate_notification_types.py from008 OpenAPI; do not edit. */"
    ]
    for name, schema in schemas.items():
        lines.extend(
            [
                f"/** Wire shape of {name}; semantic constraints are checked by the server. */",
                f"export type {name} = {wire_type(schema)};",
            ]
        )
    (root / "frontend/src/lib/api/notification-types.ts").write_text(
        "\n".join(lines) + "\n"
    )
    (root / "backend/src/ecs_ec/notifications/contract.json").write_bytes(
        source.read_bytes()
    )


if __name__ == "__main__":
    main()
